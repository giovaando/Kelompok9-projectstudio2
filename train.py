import os
import random
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Subset
from torchvision import datasets, transforms, models
from sklearn.model_selection import train_test_split
from sklearn.metrics import f1_score

def set_seed(seed=42):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True

set_seed(42)
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"[INFO] Perangkat Pelatihan: {device}")

"""### **2. Hyperparameters & Paths**"""

DATA_DIR = "/content/dataset_sampah_local"
BATCH_SIZE = 32
NUM_CLASSES = 5
EPOCHS = 15
LEARNING_RATE = 1e-4
WEIGHT_DECAY = 1e-2
NUM_WORKERS = 2
TEST_SIZE = 0.20

"""### **3. Data Augmentation & Transformations**"""

train_transform = transforms.Compose([
    transforms.RandomResizedCrop(224, scale=(0.8, 1.0)),
    transforms.RandomHorizontalFlip(p=0.5),
    transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.2),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225]
    )
])

val_transform = transforms.Compose([
    transforms.Resize(236),
    transforms.CenterCrop(224),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225]
    )
])

"""### **4. Dataset Loading & Opsi 1: In-Memory Stratified Auto-Split**"""

print(f"[INFO] Memuat dataset dari folder tunggal: {DATA_DIR}")
full_train_dataset = datasets.ImageFolder(root=DATA_DIR, transform=train_transform)
full_val_dataset   = datasets.ImageFolder(root=DATA_DIR, transform=val_transform)

targets = full_train_dataset.targets
train_idx, val_idx = train_test_split(
    np.arange(len(targets)),
    test_size=TEST_SIZE,
    random_state=42,
    stratify=targets
)

train_dataset = Subset(full_train_dataset, train_idx)
val_dataset   = Subset(full_val_dataset, val_idx)

train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True, num_workers=NUM_WORKERS, pin_memory=True)
val_loader   = DataLoader(val_dataset, batch_size=BATCH_SIZE, shuffle=False, num_workers=NUM_WORKERS, pin_memory=True)

print(f"[INFO] Total Seluruh Gambar: {len(full_train_dataset)}")
print(f"[INFO] Subset Latih (80%): {len(train_dataset)} | Subset Validasi (20%): {len(val_dataset)}")
print(f"[INFO] Indeks Kelas: {full_train_dataset.class_to_idx}")

"""### **5. Model Builder (ConvNeXt-Tiny Pretrained)**"""

def build_convnext_model(num_classes=5):
    try:
        weights = models.ConvNeXt_Tiny_Weights.DEFAULT
        model = models.convnext_tiny(weights=weights)
    except Exception:
        print("[WARNING] Tidak dapat mengunduh bobot online. Menggunakan arsitektur tanpa bobot pretrained.")
        model = models.convnext_tiny(weights=None)

    in_features = model.classifier[2].in_features
    model.classifier[2] = nn.Linear(in_features, num_classes)
    return model

model = build_convnext_model(NUM_CLASSES).to(device)

"""### **6. Optimizer, Scheduler & Criterion**"""

criterion = nn.CrossEntropyLoss()
optimizer = optim.AdamW(model.parameters(), lr=LEARNING_RATE, weight_decay=WEIGHT_DECAY)
scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=EPOCHS, eta_min=1e-6)

"""### **7. Training & Evaluation Functions**"""

def train_epoch(model, loader, criterion, optimizer, device):
    model.train()
    running_loss, correct, total = 0.0, 0, 0
    for images, targets in loader:
        images, targets = images.to(device), targets.to(device)

        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, targets)
        loss.backward()
        optimizer.step()

        running_loss += loss.item() * images.size(0)
        _, preds = outputs.max(1)
        total += targets.size(0)
        correct += preds.eq(targets).sum().item()

    return running_loss / total, correct / total

def evaluate(model, loader, criterion, device):
    model.eval()
    running_loss = 0.0
    all_preds, all_targets = [], []

    with torch.no_grad():
        for images, targets in loader:
            images, targets = images.to(device), targets.to(device)
            outputs = model(images)
            loss = criterion(outputs, targets)

            running_loss += loss.item() * images.size(0)
            _, preds = outputs.max(1)

            all_preds.extend(preds.cpu().numpy())
            all_targets.extend(targets.cpu().numpy())

    total = len(all_targets)
    epoch_loss = running_loss / total
    epoch_acc = np.mean(np.array(all_preds) == np.array(all_targets))
    macro_f1 = f1_score(all_targets, all_preds, average='macro')

    return epoch_loss, epoch_acc, macro_f1

"""### **8. Main Training Loop**"""

best_macro_f1 = 0.0
os.makedirs("submission", exist_ok=True)

print("\n=== MEMULAI PELATIHAN CONVNEXT-TINY (AUTO-SPLIT 80/20) ===")
for epoch in range(EPOCHS):
    train_loss, train_acc = train_epoch(model, train_loader, criterion, optimizer, device)
    val_loss, val_acc, val_f1 = evaluate(model, val_loader, criterion, device)

    scheduler.step()
    current_lr = optimizer.param_groups[0]['lr']

    print(f"Epoch [{epoch+1:02d}/{EPOCHS:02d}] (LR: {current_lr:.6f}) | "
          f"Train Loss: {train_loss:.4f} Acc: {train_acc*100:.2f}% | "
          f"Val Loss: {val_loss:.4f} Acc: {val_acc*100:.2f}% | "
          f"Val Macro-F1: {val_f1:.4f}")

    if val_f1 > best_macro_f1:
        best_macro_f1 = val_f1
        torch.save(model.state_dict(), "submission/model.pth")
        torch.save(model.state_dict(), "best_convnext_tiny.pth")
        print(f"  --> Checkpoint disimpan! Best Val Macro-F1: {best_macro_f1:.4f}")

print(f"\n[SELESAI] Pelatihan Selesai! Macro-F1 Terbaik: {best_macro_f1:.4f}")